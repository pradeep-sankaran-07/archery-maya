let lang = 'en';

export function initLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'no') { lang = saved; return; }
    // Share the choice made in Archery Maya, if any.
    const archery = localStorage.getItem('archery-maya.lang');
    if (archery === 'en' || archery === 'no') { lang = archery; return; }
  } catch { /* ignore */ }
  const nav = (navigator.language || '').toLowerCase();
  lang = (nav.startsWith('nb') || nav.startsWith('nn') || nav.startsWith('no')) ? 'no' : 'en';
}

export function setLang(l) {
  lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch { /* ignore */ }
}
export function getLang() { return lang; }

export function t(key, vars = {}) {
  const map = lang === 'no' ? NO : EN;
  const str = map[key] ?? EN[key] ?? key;
  return str.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
}
